/** Дата в админ-формате: «30 июн. 2026 г.»; пустое значение — длинное тире. */
export function formatAdminDate(date: Date | null | undefined) {
  if (!date) return "—";
  return new Intl.DateTimeFormat("ru-RU", { dateStyle: "medium" }).format(date);
}

/** Дата и время для журналов синхронизации и чек-инов. */
export function formatAdminDateTime(date: Date | null | undefined) {
  if (!date) return "—";
  return new Intl.DateTimeFormat("ru-RU", {
    dateStyle: "medium",
    timeStyle: "short",
  }).format(date);
}

/** Денежная сумма (значение в центах) в русской локали. */
export function formatAdminMoney(
  amountCents: number,
  currency: string,
  fractionDigits?: number,
) {
  return new Intl.NumberFormat("ru-RU", {
    style: "currency",
    currency: currency.toUpperCase(),
    ...(fractionDigits !== undefined ? { maximumFractionDigits: fractionDigits } : {}),
  }).format(amountCents / 100);
}
